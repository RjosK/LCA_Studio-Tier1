let currentLanguage = localStorage.getItem("econode_lang") || "es";

function t(key, fallback = "") {
 const dict = I18N_DICTIONARY[currentLanguage] || I18N_DICTIONARY.es;
 return dict[key] || fallback || key;
}

function applyTranslations(root = document) {
  const container = root || document;
  container.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (val) {
      if (el.hasAttribute("data-i18n-html") || val.includes("<")) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }
  });

 container.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
 const key = el.getAttribute("data-i18n-placeholder");
 const val = t(key);
 if (val) el.setAttribute("placeholder", val);
 });

 container.querySelectorAll("[data-i18n-title]").forEach(el => {
 const key = el.getAttribute("data-i18n-title");
 const val = t(key);
 if (val) el.setAttribute("title", val);
 });
}

function setLanguage(lang) {
 if (lang !== "es" && lang !== "en") lang = "es";
 currentLanguage = lang;
 localStorage.setItem("econode_lang", lang);
 document.documentElement.lang = lang;

 // Toggle active buttons
 const btnEs = document.getElementById("btnLangEs");
 const btnEn = document.getElementById("btnLangEn");
 if (btnEs) btnEs.classList.toggle("active", lang === "es");
 if (btnEn) btnEn.classList.toggle("active", lang === "en");

 applyTranslations(document);

 // Trigger app re-render of dynamic lists if app exists
 if (window.EconodeApp && typeof window.EconodeApp.onLanguageChange === "function") {
 window.EconodeApp.onLanguageChange(lang);
 }
}

window.I18n = {
 t,
 setLanguage,
 applyTranslations,
 getCurrentLanguage: () => currentLanguage,
 dict: I18N_DICTIONARY
};

if (document.readyState === "loading") {
 document.addEventListener("DOMContentLoaded", () => setLanguage(currentLanguage));
} else {
 setLanguage(currentLanguage);
}


